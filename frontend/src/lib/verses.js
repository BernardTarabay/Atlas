/**
 * ONE VERSE, ON THE SIGN-IN SCREEN, IN ARABIC.
 *
 * It is not a feature. It is a line of type under the sign-in card, and
 * everything about this file is sized to that: no ribbon, no controls, no
 * network, no second language, no stored state.
 *
 * WHY THE ROTATION IS COMPUTED, NOT STORED
 *
 * The obvious implementation is a timestamp in localStorage -- "last changed
 * at X, change again at X + 6h". That gives every browser its own private
 * schedule: two people sitting beside each other see different verses, and a
 * tab left open over a weekend shows a stale one until something re-renders.
 *
 * Instead the slot is derived from the clock itself:
 *
 *     slot = floor(now / 6h)
 *
 * the same integer everywhere at the same moment. Nothing is written, nothing
 * has to be read back, and private-mode Safari behaves like every other
 * browser because no storage is touched at all.
 *
 * WHAT WAS REMOVED, AND WHY IT WAS NOT LOAD-BEARING
 *
 * This used to fetch each verse from bolls.life at runtime, cache it in
 * localStorage, carry a King James translation alongside the Arabic, and
 * remember how far the reader had clicked ahead. The fetch never ran in the
 * deployment the client uses: helmet's default CSP is `connect-src 'self'`
 * (backend/src/app.js), so the browser refused the request, the catch
 * returned the bundled text, and nobody could tell. Roughly a hundred lines
 * of caching, aborting and HTML-stripping existed to serve a code path that
 * production blocked.
 *
 * The text below is Smith & Van Dyke (SVD), public domain, which is why it
 * can be bundled here at all.
 */

