/** The slot the wall clock is currently in. Same integer in every browser. */
export function currentSlot(now = Date.now()) {
  return Math.floor(now / SLOT_MS);
}

/** Which verse a given slot lands on. */
export function verseFor(slot) {
  return VERSES[((slot % VERSES.length) + VERSES.length) % VERSES.length];
}
